// `pages/` (or `src/pages/`) support, mapped onto the App-Router machinery:
//   pages/index.jsx, pages/blog/[slug].jsx, [...all], [[...all]]  -> PAGE routes (props from getStaticProps / getServerSideProps)
//   pages/_app.jsx      -> wraps every page in <App Component pageProps />   (through a generated layout)
//   pages/_document.jsx -> <html> / <head> / <body> customisation (see pages-document.js)
//   pages/404.jsx, pages/_error.jsx, pages/500.jsx -> not-found and error pages
//   pages/api/**        -> API routes written as (req, res) handlers (through generated adapters, see pages-api.js)
// Generated files live in .nepx-pages/ (safe to delete, gitignore it).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { NepxError } from "./errors/index.js";

export const GEN_DIR = ".nepx-pages";
export const pagesDirOf = (root) => (existsSync(path.join(root, "src", "pages")) ? path.join(root, "src", "pages") : path.join(root, "pages"));

function writeIfChanged(root, rel, content) {
  const abs = path.join(root, rel);
  try { if (readFileSync(abs, "utf8") === content) return; } catch { /* new file */ }
  mkdirSync(path.dirname(abs), { recursive: true });
  writeFileSync(abs, content);
}

/** pages/_document.* (absolute path) or null. */
export function findDocument(root, exts) {
  const dir = pagesDirOf(root);
  if (!existsSync(dir)) return null;
  const hit = readdirSync(dir).find((n) => exts.some((e) => n === "_document" + e));
  return hit ? path.join(dir, hit) : null;
}

/** Adds the routes of pages/ to the scan result of app/. H = helpers of router.js. */
export function mergePages(root, scan, H) {
  const dir = pagesDirOf(root);
  if (!existsSync(dir)) return scan;
  const prefix = path.relative(root, dir).split(path.sep).join("/");
  const files = H.walk(dir);
  const seen = new Map(scan.routes.map((r) => [r.path, r.file]));
  let appFile = null, errFile = null, notFoundFile = null, serverErr = null;
  const found = [];
  for (const rel of files) {
    const [stem] = H.splitExt(path.posix.basename(rel));
    if (rel.endsWith(".d.ts")) continue;
    const d = path.posix.dirname(rel) === "." ? "" : path.posix.dirname(rel);
    const file = `${prefix}/${rel}`;
    if (d === "") {
      if (stem === "_app") { appFile = file; continue; }
      if (stem === "_document") continue;
      if (stem === "_error") { errFile = file; continue; }
      if (stem === "404") { notFoundFile = file; continue; }
      if (stem === "500") { serverErr = file; continue; }
    }
    if (stem.startsWith("_")) continue;
    found.push({ rel, d, stem, file });
  }
  let layoutFile = null;
  if (appFile) {
    layoutFile = `${GEN_DIR}/app-layout.jsx`;
    const imp = path.posix.relative(GEN_DIR, appFile);
    writeIfChanged(root, layoutFile, `// generated by Nepx from ${appFile}\nimport React from "react";\nimport App from "${imp.startsWith(".") ? imp : "./" + imp}";\n` +
      `export default function PagesApp({ children }) {\n  const Component = children && children.type;\n  const { __nepxApp, ...pageProps } = (children && children.props) || {};\n  if (typeof Component !== "function" && typeof Component !== "object") return children;\n  return React.createElement(App, { ...(__nepxApp || {}), Component, pageProps });\n}\n`);
  }
  const chain = [...(scan.rootLayout ? [scan.rootLayout] : []), ...(layoutFile ? [layoutFile] : [])];
  const routes = [];
  for (const { rel, d, stem, file } of found) {
    const isApi = d === "api" || d.startsWith("api/") || (d === "" && stem === "api");
    const parts = [...(d ? d.split("/") : []), ...(stem === "index" ? [] : [stem])];
    let segs;
    try { segs = H.parseDirSegments(parts).segs; } catch (err) { throw new NepxError(`${file}: ${err.message}`); }
    const urlPath = H.urlPathOf(segs);
    if (seen.has(urlPath)) throw new NepxError(`Route conflict: ${file} and ${seen.get(urlPath)} both map to ${urlPath}`);
    seen.set(urlPath, file);
    const names = segs.map((s) => s.param || s.catchall || s.optional).filter(Boolean);
    if (new Set(names).size !== names.length) throw new NepxError(`${file}: duplicate parameter name`);
    const base = { path: urlPath, segments: segs, params: names, meta: null, slots: [], notFound: null, loading: null, errorScope: null, fromPages: true, ...(appFile ? { pagesApp: appFile } : {}) };
    if (isApi) {
      const gen = `${GEN_DIR}/api/${rel.slice(0, rel.length - (H.splitExt(path.posix.basename(rel))[1].length))}.js`;
      let imp = path.posix.relative(path.posix.dirname(gen), file);
      if (!imp.startsWith(".")) imp = "./" + imp;
      writeIfChanged(root, gen, `// generated by Nepx from ${file}\nimport handler, * as ns from ${JSON.stringify(imp)};\nimport { createPagesApiHandler } from "nepx";\n` +
        `const h = createPagesApiHandler(handler, ns.config, ${JSON.stringify(file)});\nexport const GET = h, POST = h, PUT = h, PATCH = h, DELETE = h, OPTIONS = h;\n`);
      routes.push({ ...base, type: "API", file: gen, methods: [], layouts: [], pagesApi: true });
    } else routes.push({ ...base, type: "PAGE", file, methods: ["GET"], layouts: chain });
  }
  const all = [...scan.routes, ...routes].sort(H.compareRoutes);
  return {
    ...scan, routes: all,
    rootLayout: scan.rootLayout ?? layoutFile,
    notFound: scan.notFound ?? notFoundFile,
    errorPage: scan.errorPage ?? errFile ?? serverErr,
  };
}
