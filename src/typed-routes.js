// config.typedRoutes: writes <project>/nepx-routes.d.ts so <Link href>, router.push() ... only accept routes that exist (compile-time only).
// Static routes become keys, dynamic ones template-literal index signatures: /users/[id] -> `/users/${string}`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export const TYPED_ROUTES_FILE = "nepx-routes.d.ts";

/** Route paths use ":id" / ":slug+" / ":slug*?": "/users/:id/edit" -> [ "/users/${string}/edit" ]; "/docs/:slug*?" -> [ "/docs", "/docs/${string}" ] */
export function routeTemplates(routePath) {
  let outs = [""];
  for (const seg of routePath.split("/").filter(Boolean)) {
    if (/^:[\w]+\*\??$/.test(seg)) outs = [...outs, ...outs.map((o) => `${o}/\${string}`)]; // optional catch-all: with and without
    else if (/^:[\w]+\+$/.test(seg) || /^:[\w]+$/.test(seg)) outs = outs.map((o) => `${o}/\${string}`);
    else outs = outs.map((o) => `${o}/${seg}`);
  }
  return outs.map((o) => o || "/");
}

export function routeTypes(routes) {
  const seen = new Set();
  for (const r of routes) if (r.type !== "API" && !r.error && typeof r.path === "string") for (const t of routeTemplates(r.path)) seen.add(t);
  const lines = [...seen].sort().map((t) => (t.includes("${") ? `    [key: \`${t}\`]: true;` : `    ${JSON.stringify(t)}: true;`));
  return `// Generated by Nepx (config.typedRoutes). Do not edit; commit it or add it to .gitignore.\nimport "nepx";\n\ndeclare module "nepx" {\n  interface NepxTypedRoutes {\n${lines.join("\n")}\n  }\n}\n`;
}

/** Write the file when typedRoutes is on (only if the content changed). Returns true when it wrote. */
export function writeTypedRoutes(root, routes, enabled) {
  if (!enabled) return false;
  const file = path.join(root, TYPED_ROUTES_FILE), text = routeTypes(routes);
  if (existsSync(file) && readFileSync(file, "utf8") === text) return false;
  writeFileSync(file, text);
  return true;
}
