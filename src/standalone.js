// config.output = "standalone": after `nepx build`, .nepx/standalone/ holds everything needed to run the app on a server:
//   .nepx/ (server code, public files, prerendered pages, client bundle), nepx.config.js, package.json, server.js.
// Deploy that one folder, run `npm install --omit=dev`, then `node server.js` (PORT / HOSTNAME env respected).
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { OUT_DIR } from "./build.js";

const SELF_VERSION = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")).version;
const SERVER_JS = `// Generated by \`nepx build\` (output: "standalone"). Run: node server.js   (PORT env or --port N)
import { main } from "nepxjs/cli";
const args = ["start"];
if (process.env.PORT && !process.argv.includes("--port")) args.push("--port", process.env.PORT);
main([...args, ...process.argv.slice(2)]).catch((err) => { console.error(\`nepx: \${err.message}\`); process.exit(1); });
`;

export function writeStandalone(root) {
  const out = path.join(root, OUT_DIR, "standalone");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(path.join(out, OUT_DIR), { recursive: true });
  for (const d of ["server", "public", "static", "client", "manifest.json"]) {
    const from = path.join(root, OUT_DIR, d);
    if (existsSync(from)) cpSync(from, path.join(out, OUT_DIR, d), { recursive: true });
  }
  if (existsSync(path.join(root, "nepx.config.js"))) cpSync(path.join(root, "nepx.config.js"), path.join(out, "nepx.config.js"));
  let pkg = {};
  try { pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8")); } catch { /* no package.json */ }
  const dependencies = { ...(pkg.dependencies ?? {}) };
  if (!dependencies.nepxjs) dependencies.nepxjs = "^" + SELF_VERSION;
  let hasClient = false;
  try { hasClient = JSON.parse(readFileSync(path.join(root, OUT_DIR, "manifest.json"), "utf8")).client === true; } catch { /* no manifest */ }
  if (hasClient) for (const m of ["react", "react-dom"]) if (!dependencies[m]) dependencies[m] = pkg.devDependencies?.[m] ?? "^19.0.0"; // pages need React at runtime
  writeFileSync(path.join(out, "package.json"), JSON.stringify({ name: pkg.name ?? "nepx-app", private: true, type: "module", version: pkg.version ?? "0.0.0", scripts: { start: "node server.js" }, dependencies }, null, 2) + "\n");
  writeFileSync(path.join(out, "server.js"), SERVER_JS);
  return out;
}
